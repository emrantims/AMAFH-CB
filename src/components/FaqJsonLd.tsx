export const FaqJsonLd: React.FC = () => {
  const { language } = useLanguage();

  useEffect(() => {
    const scriptId = 'faq-jsonld-schema';
    let scriptTag = document.getElementById(scriptId) as HTMLScriptElement | null;

    if (!scriptTag) {
      scriptTag = document.createElement('script');
      scriptTag.id = scriptId;
      scriptTag.type = 'application/ld+json';
      document.head.appendChild(scriptTag);
    }

    // Determine current language FAQ entities
    const isArabic = language === 'ar';
    const activeFaqs = isArabic
      ? ARABIC_FAQS.map((item) => ({
          '@type': 'Question',
          name: item.question,
          acceptedAnswer: {
            '@type': 'Answer',
            text: item.answer,
          },
        }))
      : FAQ_ITEMS.map((item) => ({
          '@type': 'Question',
          name: item.question,
          acceptedAnswer: {
            '@type': 'Answer',
            text: item.answer,
          },
        }));

    const schemaData = {
      '@context': 'https://schema.org',
      '@type': 'FAQPage',
      mainEntity: activeFaqs,
    };

    scriptTag.textContent = JSON.stringify(schemaData, null, 2);

    return () => {
      // Keep script in head for crawler persistence
    };
  }, [language]);

  return null;
};
